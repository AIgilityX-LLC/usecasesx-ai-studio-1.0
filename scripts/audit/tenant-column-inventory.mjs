#!/usr/bin/env node
/**
 * Inventory CREATE TABLE public.* in migrations for tenancy/audit columns.
 * Report-only — does not migrate. tenant_id in product language = organization_id
 * and/or workspace_id (see docs/security/phase-3-hardening.md).
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = "supabase/migrations";
const CREATE = /CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?public\.([a-zA-Z0-9_]+)\s*\(([\s\S]*?)\);/gi;

const rows = [];
for (const file of readdirSync(DIR).filter((f) => f.endsWith(".sql")).sort()) {
  const sql = readFileSync(join(DIR, file), "utf8");
  for (const m of sql.matchAll(CREATE)) {
    const table = m[1];
    const body = m[2].toLowerCase();
    rows.push({
      table,
      file,
      workspace_id: /\bworkspace_id\b/.test(body),
      organization_id: /\borganization_id\b/.test(body),
      created_by: /\bcreated_by\b/.test(body),
      created_at: /\bcreated_at\b/.test(body),
      updated_by: /\bupdated_by\b/.test(body),
      updated_at: /\bupdated_at\b/.test(body),
    });
  }
}

const missing = rows.filter(
  (r) =>
    !(r.workspace_id || r.organization_id) ||
    !r.created_at ||
    !r.created_by ||
    !r.updated_at,
);

const md = [
  "# Tenant / audit column inventory (from migrations)",
  "",
  "Generated by `scripts/audit/tenant-column-inventory.mjs`. **Not live DB truth.**",
  "",
  "| Table | ws | org | created_by | created_at | updated_by | updated_at | Migration |",
  "| ----- | -- | --- | ---------- | ---------- | ---------- | ---------- | --------- |",
  ...rows.map(
    (r) =>
      `| \`${r.table}\` | ${r.workspace_id ? "Y" : "·"} | ${r.organization_id ? "Y" : "·"} | ${r.created_by ? "Y" : "·"} | ${r.created_at ? "Y" : "·"} | ${r.updated_by ? "Y" : "·"} | ${r.updated_at ? "Y" : "·"} | \`${r.file}\` |`,
  ),
  "",
  `Tables missing ws/org **or** created_by/at **or** updated_at: **${missing.length}** / ${rows.length}`,
  "",
  "Follow-up: additive migrations only for gaps that are tenant business tables; do not rename `workspace_id` → `tenant_id`.",
  "",
];

writeFileSync("docs/security/tenant-column-inventory.md", md.join("\n"));
console.log(JSON.stringify({ tables: rows.length, gaps: missing.length }, null, 2));
